# Builds src/Plainlines.mq5 (or another .mq5) with MetaEditor under Wine, no terminal.
# Usage: ./build.sh [--release|--dev] [--keep] [--skip-audit] [--include] [path/to/File.mq5]
#   (none)        demo build, trades only on a demo account -> build/PlainlinesDemo.ex5
#   --dev         dev build (dev.log, command channel), demo only -> build/PlainlinesDev.ex5
#   --release     build for real accounts, committed sources only -> build/Plainlines.ex5
#   --keep        keep the temporary build root and Wine prefix (default: removed always)
#   --skip-audit  only for spike and probe sources, refused for src/Plainlines.mq5
#   --include     use /include:<MQL5 dir> instead of /portable (experiment)
# Needs ~/.local/share/plainlines-build (run tools/setup-build-env.sh once). That folder
# is never modified: every build uses a fresh temporary root and a fresh empty Wine prefix.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS="${PLAINLINES_BUILD_DIR:-$HOME/.local/share/plainlines-build}"
KEEP=0; SKIP_AUDIT=0; MODE=portable; TARGET=""; DEV=0; REL=0
SRCPATHS=(src)
RELPATHS=("${SRCPATHS[@]}" build.sh audit.sh)
for a in "$@"; do
  case "$a" in
    --keep) KEEP=1;;
    --skip-audit) SKIP_AUDIT=1;;
    --release) REL=1;;
    --dev) DEV=1;;
    --include) MODE=include;;
    -h|--help) awk 'NR>4 && /^#/ { sub(/^# ?/, ""); print; next } NR>4 { exit }' "$0"; exit 0;;
    -*) echo "build: unknown option $a" >&2; exit 2;;
    *) TARGET="$a";;
  esac
done

[[ -f "$TOOLS/MetaEditor64.exe" && -d "$TOOLS/MQL5/Include" ]] || { echo "build: $TOOLS is not set up, run tools/setup-build-env.sh" >&2; exit 1; }
command -v wine >/dev/null || { echo "build: wine not found" >&2; exit 1; }

if [[ -z "$TARGET" ]]; then
  SRC_DIR="$ROOT/src"; MAIN="Plainlines.mq5"; AUDIT_PATH="$ROOT/src"; OUT_BASE="Plainlines"; LOG_NAME="build.log"
else
  [[ -f "$TARGET" ]] || { echo "build: no such file: $TARGET" >&2; exit 1; }
  TARGET="$(realpath "$TARGET")"
  SRC_DIR="$(dirname "$TARGET")"; MAIN="$(basename "$TARGET")"; AUDIT_PATH="$SRC_DIR"; OUT_BASE="${MAIN%.*}"; LOG_NAME="$OUT_BASE.log"
  [[ "$TARGET" == "$ROOT/src/Plainlines.mq5" ]] && { SRC_DIR="$ROOT/src"; AUDIT_PATH="$ROOT/src"; LOG_NAME="build.log"; }
fi

MAINTARGET=0
[[ -z "$TARGET" || "$TARGET" == "$ROOT/src/Plainlines.mq5" ]] && MAINTARGET=1
[[ $REL -eq 1 && $DEV -eq 1 ]] && { echo "build: --release and --dev exclude each other" >&2; exit 2; }
[[ $((REL+DEV)) -gt 0 && $MAINTARGET -eq 0 ]] && { echo "build: --release/--dev only for src/Plainlines.mq5" >&2; exit 2; }
[[ $SKIP_AUDIT -eq 1 && $MAINTARGET -eq 1 ]] && { echo "build: --skip-audit is not allowed for src/Plainlines.mq5" >&2; exit 2; }
BMODE=demo; BOUT=PlainlinesDemo
[[ $DEV -eq 1 ]] && { BMODE=dev; BOUT=PlainlinesDev; }
[[ $REL -eq 1 ]] && { BMODE=release; BOUT=Plainlines; }
if [[ $REL -eq 1 ]]; then
  if git -C "$ROOT" rev-parse >/dev/null 2>&1 \
     && git -C "$ROOT" diff --quiet HEAD -- "${RELPATHS[@]}" \
     && [[ -z "$(git -C "$ROOT" ls-files --others --exclude-standard "${SRCPATHS[@]}")" ]]; then
    echo "build: release of commit $(git -C "$ROOT" rev-parse --short HEAD)"
  else
    echo "build: --release needs committed sources ($(IFS=,; echo "${RELPATHS[*]}" | sed 's/,/, /g'))" >&2; exit 2
  fi
fi

if [[ $SKIP_AUDIT -eq 0 ]]; then
  "$ROOT/audit.sh" "$AUDIT_PATH" || { echo "build: audit failed, not compiling" >&2; exit 1; }
else
  echo "build: audit skipped"
fi

BR="$(mktemp -d)"; PFX="$(mktemp -d)"
case "$PFX" in *wineprefixes*|*" "*) echo "build: unsafe prefix path $PFX" >&2; exit 1;; esac
OK=0
cleanup() {
  WINEPREFIX="$PFX" wineserver -k >/dev/null 2>&1 || true
  if [[ $KEEP -eq 1 ]]; then echo "build: kept build root $BR and prefix $PFX"
  else find "$BR" "$PFX" -type d -exec chmod u+w {} + 2>/dev/null || true; rm -rf "$BR" "$PFX"; fi
}
trap cleanup EXIT

# Build root: MetaEditor is hardlinked (or copied), Include is copied so the persistent folder is never written.
ln "$TOOLS/MetaEditor64.exe" "$BR/MetaEditor64.exe" 2>/dev/null || cp "$TOOLS/MetaEditor64.exe" "$BR/MetaEditor64.exe"
mkdir -p "$BR/MQL5/Experts/Plainlines"
cp -r --no-preserve=mode "$TOOLS/MQL5/Include" "$BR/MQL5/Include"
chmod -R u+w "$BR/MQL5/Experts"
if [[ -z "$TARGET" || "$TARGET" == "$ROOT/src/Plainlines.mq5" ]]; then
  cp -r "$ROOT/src/." "$BR/MQL5/Experts/Plainlines/"
  chmod -R u+w "$BR/MQL5/Experts"
  { printf '// build mode: %s (generated by build.sh)\r\n' "$BMODE"
    [[ $DEV -eq 1 ]] && printf '#define PL_DEV_LOG\r\n'
    [[ $REL -eq 1 ]] && printf '#define PL_RELEASE\r\n'
    true; } > "$BR/MQL5/Experts/Plainlines/Build.mqh"
else
  ( cd "$SRC_DIR" && find . -type f ! -name '*.log' ! -name '*.ex5' -print0 | xargs -0 -I{} cp --parents {} "$BR/MQL5/Experts/Plainlines/" )
fi
chmod -R u+w "$BR/MQL5/Experts"

winpath() { printf 'Z:%s' "$(printf '%s' "$1" | sed 's|/|\\|g')"; }
SRC_IN_BR="$BR/MQL5/Experts/Plainlines/$MAIN"
EX5="$BR/MQL5/Experts/Plainlines/$OUT_BASE.ex5"
LOG="$BR/build.log"
MARK="$BR/.start"; touch "$MARK"; sleep 0.05

if [[ "$MODE" == portable ]]; then MODEARG="/portable"; else MODEARG="/include:$(winpath "$BR/MQL5")"; fi

# Wine exits 1 even on success, so its exit code is ignored; the log decides.
( cd "$BR" && WINEPREFIX="$PFX" WINEDEBUG=-all WINEDLLOVERRIDES="mscoree,mshtml=d" \
  timeout 180 wine MetaEditor64.exe "$MODEARG" "/compile:$(winpath "$SRC_IN_BR")" "/log:$(winpath "$LOG")" >/dev/null 2>&1 ) || true

[[ -f "$LOG" ]] || { echo "build: FAIL, MetaEditor produced no log" >&2; exit 1; }
iconv -f utf-16 -t utf-8 "$LOG" | sed 's/\r$//' > "$BR/build.utf8.log"
mkdir -p "$ROOT/build"; cp "$BR/build.utf8.log" "$ROOT/build/$LOG_NAME"

RESULT="$(grep -E 'Result: [0-9]+ errors' "$BR/build.utf8.log" | tail -1 || true)"
if ! grep -q 'Result: 0 errors' "$BR/build.utf8.log"; then
  echo "build: FAIL, no 'Result: 0 errors' in log ($ROOT/build/$LOG_NAME)" >&2
  grep -E 'error' "$BR/build.utf8.log" | head -20 >&2 || true
  exit 1
fi
[[ -f "$EX5" ]] || { echo "build: FAIL, $OUT_BASE.ex5 was not produced" >&2; exit 1; }
[[ "$EX5" -nt "$MARK" ]] || { echo "build: FAIL, $OUT_BASE.ex5 is not newer than the build start (stale)" >&2; exit 1; }

if [[ $MAINTARGET -eq 1 ]]; then OUT_BASE="$BOUT"; cp "$EX5" "$ROOT/build/$OUT_BASE.ex5"; echo "build: mode $BMODE"
else cp "$EX5" "$ROOT/build/$OUT_BASE.ex5"; fi
WARN="$(sed -n 's/.*Result: [0-9]* errors, \([0-9]*\) warnings.*/\1/p' "$BR/build.utf8.log" | tail -1)"
echo "build: OK ($MODE), ${RESULT#*Result: }"
echo "build: warnings: ${WARN:-unknown}"
echo "build: $ROOT/build/$OUT_BASE.ex5 ($(stat -c %s "$ROOT/build/$OUT_BASE.ex5") bytes)"
echo "sha256: $(sha256sum "$ROOT/build/$OUT_BASE.ex5" | cut -d' ' -f1)"
